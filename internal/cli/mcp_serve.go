package cli

import (
	"fmt"
	"os"

	"github.com/openexec/openexec/internal/infra"
	"github.com/openexec/openexec/internal/mcp"
	"github.com/spf13/cobra"
)

func init() {
	rootCmd.AddCommand(mcpServeCmd)
}

var mcpServeCmd = &cobra.Command{
	Use:   "mcp-serve",
	Short: "Run the OpenExec MCP server (signals + story backlog for light-mode clients)",
	Long: `Run the OpenExec MCP server over stdio.

Exposes the orchestrator control plane (openexec_signal, openexec_result) and
the story backlog (backlog_list_stories, backlog_get_story, backlog_claim_story,
backlog_complete_task, backlog_complete_story) plus project memory (memory_read).

This is the light-mode entry point: an external MCP client such as Claude Code
can read the backlog generated by the heavy pipeline and work it one story at
a time, without booting the OpenExec daemon. See docs/LIGHT_MODE.md.`,
	RunE: func(cmd *cobra.Command, args []string) error {
		// Get workspace from current directory or WORKSPACE_ROOT
		workDir, _ := os.Getwd()
		srv, err := mcp.NewServerWithConfig(os.Stdin, os.Stdout, mcp.ServerConfig{
			WorkDir: workDir,
			Mode:    os.Getenv("OPENEXEC_MODE"),
		})
		if err != nil {
			fmt.Fprintf(os.Stderr, "MCP server error: %v\n", err)
			fmt.Fprintf(os.Stderr, "Hint: Set WORKSPACE_ROOT env var or run from a valid project directory\n")
			return err
		}

		// Infra tools (SRE command registry): enabled only when the operator
		// wrote .openexec/infra.yaml. A malformed allowlist fails the server
		// loudly — a security config must never half-load.
		infraReg, err := infra.LoadRegistry(workDir)
		if err != nil {
			fmt.Fprintf(os.Stderr, "infra allowlist error: %v\n", err)
			return err
		}
		if infraReg != nil {
			srv.SetInfraRegistry(infraReg)
		}

		return srv.Serve()
	},
}
